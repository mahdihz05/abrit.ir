from __future__ import annotations

from functools import wraps

from django.contrib.auth.models import Permission
from drf_spectacular.utils import extend_schema
from rest_framework.exceptions import NotFound
from rest_framework.response import Response
from rest_framework.views import APIView

from .auth_api import admin_session_required, error
from .role_catalog_serializers import (
    PermissionListResponseSerializer,
    RoleListResponseSerializer,
    RoleResponseSerializer,
)
from .roles import ROLE_DEFINITIONS, ROLE_BY_KEY


ROLE_DESCRIPTIONS = {
    "editor": "Edit non-published content and media in the administration surfaces.",
    "publisher": "Edit content and control publication, archive, and scheduling transitions.",
    "submission-reviewer": "Review and manage form submissions and their attached files.",
    "auditor": "Read administration and audit information without Django Admin access.",
}

# These are declared by the Phase 1 capability/content models rather than
# generated by Django's standard add/change/delete/view permission set.
CUSTOM_PERMISSION_KEYS = {
    "accounts.access_admin",
    "accounts.view_dashboard",
    "accounts.view_role_catalog",
    "content.publish_contenttranslation",
}


def _catalog_permission(user) -> bool:
    return user.is_superuser or user.has_perm("accounts.view_role_catalog")


def role_catalog_required(view):
    @wraps(view)
    @admin_session_required
    def wrapped(self, request, *args, **kwargs):
        if not _catalog_permission(request.user):
            return error(
                "permission_denied",
                "You are not allowed to view the role and permission catalog.",
                403,
            )
        return view(self, request, *args, **kwargs)

    return wrapped


def _role_data(role):
    return {
        "key": role.key,
        "name": role.name,
        "description": ROLE_DESCRIPTIONS[role.key],
        "reserved": True,
        "requires_django_staff": role.requires_django_staff,
        "permissions": sorted(role.permissions),
    }


def _permission_data():
    keys = sorted({permission for role in ROLE_DEFINITIONS for permission in role.permissions})
    permission_map = {
        f"{permission.content_type.app_label}.{permission.codename}": permission
        for permission in Permission.objects.select_related("content_type").filter(
            content_type__app_label__in={key.split(".", 1)[0] for key in keys},
            codename__in={key.split(".", 1)[1] for key in keys},
        )
    }
    # A missing row means migrations/post_migrate have not completed. Do not
    # invent a label or silently expose a catalog that cannot be provisioned.
    if set(permission_map) != set(keys):
        return []
    return sorted(
        (
            {
                "key": key,
                "label": permission_map[key].name,
                "category": permission_map[key].content_type.app_label,
                "source": "custom" if key in CUSTOM_PERMISSION_KEYS else "django",
            }
            for key in keys
        ),
        key=lambda item: (item["category"], item["key"]),
    )


class RoleListView(APIView):
    @extend_schema(
        operation_id="admin_role_catalog_list",
        responses=RoleListResponseSerializer,
    )
    @role_catalog_required
    def get(self, request):
        return Response({"data": [_role_data(role) for role in ROLE_DEFINITIONS]})


class RoleDetailView(APIView):
    @extend_schema(
        operation_id="admin_role_catalog_detail",
        responses=RoleResponseSerializer,
    )
    @role_catalog_required
    def get(self, request, key):
        role = ROLE_BY_KEY.get(key)
        if role is None:
            raise NotFound("The requested role does not exist.")
        return Response({"data": _role_data(role)})


class PermissionListView(APIView):
    @extend_schema(
        operation_id="admin_permission_catalog_list",
        responses=PermissionListResponseSerializer,
    )
    @role_catalog_required
    def get(self, request):
        return Response({"data": _permission_data()})
